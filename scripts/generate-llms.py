#!/usr/bin/env python3
"""Generate the documentation index, compatibility alias and consolidated LLM guide."""
from pathlib import Path
import argparse
import re

ROOT = Path(__file__).resolve().parent.parent
RAW = 'https://raw.githubusercontent.com/PROMLEE/promecapt/main/'
SECTIONS = {
    'Getting started': [
        ('README.md', 'English overview', 'Features, defaults, privacy and installation choices.'),
        ('README.ko.md', '한국어 안내', '한국어 제품 소개와 사용법.'),
        ('README.ja.md', '日本語ガイド', '日本語の機能・インストール・使い方.'),
        ('README.zh-CN.md', '简体中文指南', '功能、安装及使用说明。'),
        ('docs/USAGE.md', 'Usage guide', 'Shortcuts, GIF controls, local storage and privacy.'),
        ('docs/INSTALL.md', 'Build and install without a developer account', 'Free Apple tools, local ad-hoc build, app installation, permissions and troubleshooting.'),
        ('docs/INSTALL.ko.md', '개발자 계정 없는 설치 가이드', '무료 개발 도구·로컬 빌드·설치·권한·문제 해결.'),
    ],
    'Capabilities and trust': [
        ('docs/FEATURES.md', 'Feature matrix', 'Supported features and their limits; UI language and OCR language are separate.'),
        ('docs/releases/1.0.0.md', '1.0.0 release notes', 'Initial release scope, macOS requirements and ad-hoc signing status.'),
        ('SECURITY.md', 'Security', 'Local processing, permissions and reporting guidance.'),
        ('LICENSE', 'MIT license', 'Terms for personal and commercial use, modification and redistribution.'),
    ],
    'Development': [
        ('CONTRIBUTING.md', 'Contributing', 'Build checks, translations, contribution scope and private screen content.'),
        ('docs/QA.md', 'Testing', 'Automated checks and manual acceptance flows.'),
        ('docs/RELEASING.md', 'Release workflow', 'Architecture builds, checksums and signing / publishing steps.'),
        ('CHANGELOG.md', 'Changelog', 'Public release history.'),
    ],
    'Optional': [
        ('llms-full.txt', 'Consolidated guide', 'English overview, full local installation guide, feature limits, security and license in one file.'),
        ('docs/AUTO-UPDATE.md', 'Future updater design', 'Design only; automatic updates are not implemented in 1.0.0.'),
    ],
}
FULL_FILES = ['README.md', 'docs/INSTALL.md', 'docs/USAGE.md', 'docs/FEATURES.md', 'CONTRIBUTING.md', 'SECURITY.md', 'LICENSE']


def raw_links(text, source):
    """Keep relative Markdown and HTML asset links usable outside the repository viewer."""
    def url(ref):
        if re.match(r'^[a-z]+:', ref) or ref.startswith('#'):
            return ref
        path, marker, anchor = ref.partition('#')
        relative = (source.parent / path).resolve().relative_to(ROOT)
        return RAW + relative.as_posix() + (marker + anchor if marker else '')
    text = re.sub(r'\]\(([^)]+)\)', lambda m: '](' + url(m[1]) + ')', text)
    return re.sub(r'src="([^"]+)"', lambda m: 'src="' + url(m[1]) + '"', text)


def generated():
    parts = ['# Promecapt', '', '> An MIT-licensed, open-source alternative to proprietary macOS screenshot tools: capture, editable annotations, floating image / GIF pins, region OCR and GIF recording.', '',
             'Current public release: 1.0.0. macOS 13+, Apple Silicon and Intel. Build locally with free Apple command-line tools; no paid Apple Developer account is required. Downloaded packages are ad-hoc signed, not Developer ID signed or notarized. Managed Mac policies still apply.', '',
             'Processing is local. History includes full display snapshots. UI languages: Korean, English, Japanese and Simplified Chinese. OCR recognition: Korean and English. Automatic updates and GIF frame editing are not implemented.', '']
    for heading, links in SECTIONS.items():
        parts += ['## ' + heading, '']
        parts += [f'- [{title}]({RAW}{path}): {note}' for path, title, note in links]
        parts.append('')
    index = '\n'.join(parts)
    full = '# Promecapt — consolidated documentation\n\nGenerated from maintained project documentation. Regenerate with `python3 scripts/generate-llms.py`; do not edit this file directly.\n'
    for filename in FULL_FILES:
        source = ROOT / filename
        full += '\n\n---\n\nSource: ' + RAW + filename + '\n\n' + raw_links(source.read_text(), source).strip() + '\n'
    alias = index.replace('Current public release:', 'Canonical index: ' + RAW + 'llms.txt\n\nCurrent public release:', 1)
    return {'llms.txt': index, 'llm.txt': alias, 'llms-full.txt': full}


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true', help='Fail when generated files are stale')
    args = parser.parse_args()
    for name, content in generated().items():
        file = ROOT / name
        if args.check:
            if not file.exists() or file.read_text() != content:
                raise SystemExit(f'{name} is stale; run python3 scripts/generate-llms.py')
        else:
            file.write_text(content)
    print('LLM documentation is current' if args.check else 'Generated llms.txt, llm.txt and llms-full.txt')


if __name__ == '__main__':
    main()
